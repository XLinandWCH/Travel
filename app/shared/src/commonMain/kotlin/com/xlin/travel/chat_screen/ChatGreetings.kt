package com.xlin.travel.chat_screen

/**
 * 全新对话（空界面）的欢迎语集合。
 * 每次进入空会话时随机展示一条，居中显示，避免聊天区空荡荡。
 */
internal object ChatGreetings {

    private val sentences = listOf(
        // —— 旅行小文案 ——
        "山海不远，我们出发吧。",
        "把地图摊开，下一站随你选。",
        "阳光、微风，还有一个未知的目的地。",
        "不必远方，好风景有时就在拐角。",
        "带上好奇，剩下的交给我。",

        // —— 古诗词化用（温柔不端着）——
        "春风十里，不如你开口说想去哪儿。",           // 化用 杜牧《赠别》
        "行到水穷处，坐看云起时。",       // 王维《终南别业》
        "此心安处，便是归途。",                       // 苏轼《定风波》
        "且将新火试新茶，诗酒趁年华。",               // 苏轼《望江南》
        "长风破浪会有时，我们出发吧！",       // 李白《行路难》
        "莫道桑榆晚，为霞尚满天，想去就趁现在。",     // 刘禹锡《酬乐天咏老见示》
    )

    /** 随机取一条欢迎语 */
    fun random(): String = sentences.random()
}
